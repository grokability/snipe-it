<?php

namespace App\Http\Controllers\Api;

use App\Helpers\Helper;
use App\Http\Controllers\Controller;
use App\Http\Transformers\CustomFieldsetsTransformer;
use App\Http\Transformers\CustomFieldsTransformer;
use App\Models\AssetModel;
use App\Models\CustomField;
use App\Models\CustomFieldset;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;

/**
 * This controller handles all actions related to Custom Asset Fieldsets for
 * the Snipe-IT Asset Management application.
 *
 * @todo Improve documentation here.
 * @todo Check for raw DB queries and try to convert them to query builder statements
 *
 * @version    v2.0
 *
 * @author [Brady Wetherington] [<uberbrady@gmail.com>]
 * @author [Josh Gibson]
 */
class CustomFieldsetsController extends Controller
{
    /**
     * Shows the given fieldset and its fields
     *
     * @author [A. Gianotto] [<snipe@snipe.net>]
     * @author [Josh Gibson]
     *
     * @since [v1.8]
     */
    public function index(Request $request): array
    {
        $this->authorize('index', CustomField::class);

        $allowed_columns = [
            'id',
            'name',
            'fields_count',
            'models_count',
            'created_at',
            'updated_at',
        ];

        // Inner 'fields' load pulls fieldset + adminuser on each row
        // and aggregates fieldset_count. Without those, CustomFieldsTransformer
        // lazy-loads $field->fieldset, $field->adminuser, and runs a
        // fieldset()->count() in isDeletable() per field - three extra
        // queries per field, per fieldset, on the index payload.
        $fieldsets = CustomFieldset::withCount('fields as fields_count', 'models as models_count')
            ->with([
                'fields' => fn ($q) => $q
                    ->withCount('fieldset as fieldset_count')
                    ->with(['fieldset', 'adminuser']),
                'models',
                'adminuser',
            ]);

        if ($request->filled('search')) {
            $search = $request->input('search');
            $fieldsets->where(function ($q) use ($search) {
                $q->where('name', 'LIKE', '%'.$search.'%')
                    ->orWhereHas('models', function ($m) use ($search) {
                        $m->where('models.name', 'LIKE', '%'.$search.'%')
                            ->orWhere('models.model_number', 'LIKE', '%'.$search.'%');
                    });
            });
        }

        // Advanced-search filter[] params. The fk `models` widget is
        // declared via filterableFields(). Text filters for every
        // searchable: true column (currently just `name`) are
        // auto-generated by the modal.
        $filter = $request->input('filter', []);
        if (is_string($filter)) {
            $decoded = json_decode($filter, true);
            $filter = is_array($decoded) ? $decoded : [];
        }
        if (! empty($filter['models'])) {
            // select2-checkboxes widgets write the carrier as a CSV
            // string, so split before whereIn.
            $modelIds = is_array($filter['models'])
                ? $filter['models']
                : array_values(array_filter(array_map('trim', explode(',', (string) $filter['models'])), 'strlen'));
            if (! empty($modelIds)) {
                $fieldsets->whereHas('models', function ($m) use ($modelIds) {
                    $m->whereIn('models.id', $modelIds);
                });
            }
        }
        if (array_key_exists('name', $filter) && $filter['name'] !== '' && $filter['name'] !== null) {
            $values = is_array($filter['name']) ? $filter['name'] : [$filter['name']];
            $fieldsets->where(function ($q) use ($values) {
                foreach ($values as $v) {
                    $q->orWhere('name', 'LIKE', '%'.$v.'%');
                }
            });
        }

        if (! empty($filter['created_by'])) {
            $userIds = is_array($filter['created_by'])
                ? $filter['created_by']
                : array_values(array_filter(array_map('trim', explode(',', (string) $filter['created_by'])), 'strlen'));
            if (! empty($userIds)) {
                $fieldsets->whereIn('created_by', $userIds);
            }
        }

        $total = $fieldsets->count();
        $offset = ($request->input('offset') > $total) ? $total : app('api_offset_value');
        $limit = app('api_limit_value');

        $order = $request->input('order') === 'asc' ? 'asc' : 'desc';
        $sort = in_array($request->input('sort'), $allowed_columns) ? $request->input('sort') : 'name';
        $fieldsets->orderBy($sort, $order);

        $fieldsets = $fieldsets->skip($offset)->take($limit)->get();

        return (new CustomFieldsetsTransformer)->transformCustomFieldsets($fieldsets, $total);
    }

    /**
     * Shows the given fieldset and its fields
     *
     * @author [A. Gianotto] [<snipe@snipe.net>]
     * @author [Josh Gibson]
     *
     * @param  int  $id
     *
     * @since [v1.8]
     */
    public function show($id): JsonResponse|array
    {
        $this->authorize('view', CustomField::class);
        if ($fieldset = CustomFieldset::find($id)) {
            return (new CustomFieldsetsTransformer)->transformCustomFieldset($fieldset);
        }

        return response()->json(Helper::formatStandardApiResponse('error', null, trans('admin/custom_fields/message.fieldset.does_not_exist')), 200);
    }

    /**
     * Update the specified resource in storage.
     *
     * @author [A. Gianotto] [<snipe@snipe.net>]
     *
     * @since [v4.0]
     *
     * @param  int  $id
     */
    public function update(Request $request, $id): JsonResponse
    {
        $this->authorize('update', CustomField::class);
        $fieldset = CustomFieldset::findOrFail($id);
        $fieldset->fill($request->all());

        if ($fieldset->save()) {
            return response()->json(Helper::formatStandardApiResponse('success', $fieldset, trans('admin/custom_fields/message.fieldset.update.success')));
        }

        return response()->json(Helper::formatStandardApiResponse('error', null, $fieldset->getErrors()));
    }

    /**
     * Store a newly created resource in storage.
     *
     * @author [A. Gianotto] [<snipe@snipe.net>]
     *
     * @since [v4.0]
     */
    public function store(Request $request): JsonResponse
    {
        $this->authorize('create', CustomField::class);
        $fieldset = new CustomFieldset;
        $fieldset->fill($request->all());

        if ($fieldset->save()) {
            // Sync fieldset with auto_add_to_fieldsets
            $fields = CustomField::select('id')->where('auto_add_to_fieldsets', '=', '1')->get();

            if ($fields->count() > 0) {

                foreach ($fields as $field) {
                    $field_ids[] = $field->id;
                }

                $fieldset->fields()->sync($field_ids);
            }

            return response()->json(Helper::formatStandardApiResponse('success', $fieldset, trans('admin/custom_fields/message.fieldset.create.success')));
        }

        return response()->json(Helper::formatStandardApiResponse('error', null, $fieldset->getErrors()));
    }

    /**
     * Delete a custom fieldset.
     *
     * @author [A. Gianotto] [<snipe@snipe.net>]
     *
     * @since [v4.0]
     */
    public function destroy($id): JsonResponse
    {
        $this->authorize('delete', CustomField::class);
        $fieldset = CustomFieldset::findOrFail($id);

        $fieldsCount = $fieldset->fields->count();

        if (! $fieldset->isDeletable() || ($fieldsCount > 0)) {
            return response()->json(Helper::formatStandardApiResponse('error', null, 'Fieldset is in use.'));
        }

        if ($fieldset->delete()) {
            return response()->json(Helper::formatStandardApiResponse('success', null, trans('admin/custom_fields/message.fieldset.delete.success')));
        }

        return response()->json(Helper::formatStandardApiResponse('error', null, 'Unspecified error'));
    }

    /**
     * Return JSON containing a list of fields belonging to a fieldset.
     *
     * @author [V. Cordes] [<volker@fdatek.de>]
     *
     * @since [v4.1.10]
     *
     * @param  $fieldsetId
     * @return string JSON
     */
    public function fields($id): array
    {
        $this->authorize('view', CustomField::class);
        $set = CustomFieldset::findOrFail($id);
        $fields = $set->fields;

        return (new CustomFieldsTransformer)->transformCustomFields($fields, $fields->count());
    }

    /**
     * Return JSON containing a list of fields belonging to a fieldset with the
     * default values for a given model
     *
     * @return string JSON
     */
    public function fieldsWithDefaultValues($fieldsetId, $modelId): array
    {
        $this->authorize('view', CustomField::class);
        $set = CustomFieldset::findOrFail($fieldsetId);

        $fields = $set->fields;
        $owner = AssetModel::with('defaultValues')->find($modelId);

        return (new CustomFieldsTransformer)->transformCustomFields($fields, $fields->count(), $owner);
    }
}
